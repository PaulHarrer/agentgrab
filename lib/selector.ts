/**
 * Generation of stable, human-readable locators for a picked element.
 *
 * The goal is not just "a selector that works", but one an AI agent can map
 * back to source code: prefer test ids and semantic attributes over
 * framework-generated class hashes and positional indexes.
 */

/** Attributes that usually survive a rebuild, in order of preference. */
const STABLE_ATTRS = [
  'data-testid',
  'data-test-id',
  'data-test',
  'data-cy',
  'data-qa',
  'data-component',
  'data-id',
  'data-name',
  'name',
  'aria-label',
  'placeholder',
  'alt',
  'title',
  'type',
  'href',
] as const;

/** Class names generated by build tools — useless for locating source. */
const UNSTABLE_CLASS_PATTERNS = [
  /^(css|sc|jsx|emotion|styled|makeStyles)-[a-z0-9]{4,}$/i,
  /^[\w-]+__[\w-]+___[\w-]{4,}$/, // CSS modules (long form)
  /^[\w-]+_[\w-]+__[a-zA-Z0-9]{4,}$/, // CSS modules (webpack/next)
  /^svelte-[a-z0-9]{5,}$/,
  /^v-[a-f0-9]{8}$/, // Vue scoped
  /^ng-tns-c\d+/, // Angular
  /^_[a-zA-Z0-9]{6,}$/,
];

export function isStableClass(cls: string): boolean {
  if (!cls || cls.length > 60) return false;
  return !UNSTABLE_CLASS_PATTERNS.some((re) => re.test(cls));
}

function esc(value: string): string {
  return typeof CSS !== 'undefined' && CSS.escape
    ? CSS.escape(value)
    : value.replace(/[^\w-]/g, (c) => `\\${c}`);
}

function escAttrValue(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/** The root a selector must be unique within (document, or a shadow root). */
function rootOf(el: Element): Document | ShadowRoot {
  const root = el.getRootNode();
  return root instanceof ShadowRoot ? root : el.ownerDocument;
}

function isUnique(el: Element, selector: string): boolean {
  try {
    const matches = rootOf(el).querySelectorAll(selector);
    return matches.length === 1 && matches[0] === el;
  } catch {
    return false;
  }
}

function tagOf(el: Element): string {
  return el.localName || el.tagName.toLowerCase();
}

/** Candidate selectors for a single element, most meaningful first. */
function segmentsFor(el: Element): string[] {
  const tag = tagOf(el);
  const out: string[] = [];

  const id = el.getAttribute('id');
  if (id && /^[A-Za-z][\w:.-]*$/.test(id)) out.push(`#${esc(id)}`);

  for (const attr of STABLE_ATTRS) {
    const value = el.getAttribute(attr);
    if (!value || value.length > 100) continue;
    // `href`/`title` only help when they're short and distinctive.
    if ((attr === 'href' || attr === 'title') && value.length > 60) continue;
    out.push(`${tag}[${attr}="${escAttrValue(value)}"]`);
  }

  const classes = stableClasses(el);
  if (classes.length > 0) {
    out.push(tag + classes.slice(0, 3).map((c) => `.${esc(c)}`).join(''));
    if (classes.length > 1) out.push(`${tag}.${esc(classes[0]!)}`);
  }

  const role = el.getAttribute('role');
  if (role) out.push(`${tag}[role="${escAttrValue(role)}"]`);

  out.push(tag);
  return out;
}

export function stableClasses(el: Element): string[] {
  return Array.from(el.classList).filter(isStableClass);
}

/** Position among same-tag siblings, as `:nth-of-type(n)`. */
function nthOfType(el: Element): string {
  const parent = el.parentElement;
  const tag = tagOf(el);
  if (!parent) return tag;
  const sameTag = Array.from(parent.children).filter((c) => tagOf(c) === tag);
  if (sameTag.length < 2) return tag;
  return `${tag}:nth-of-type(${sameTag.indexOf(el) + 1})`;
}

/**
 * Shortest selector that uniquely identifies `el` within its root.
 * Walks up the tree, only adding ancestors while the selector is ambiguous.
 */
export function cssSelectorFor(el: Element): string {
  if (el.nodeType !== Node.ELEMENT_NODE) return '';

  for (const segment of segmentsFor(el)) {
    if (isUnique(el, segment)) return segment;
  }

  const parts: string[] = [];
  let current: Element | null = el;
  let depth = 0;

  while (current && depth < 12) {
    const candidates = segmentsFor(current);
    let segment = candidates[0] ?? tagOf(current);

    // Within the parent, is this segment enough to single the element out?
    const parent: Element | null = current.parentElement;
    if (parent) {
      const distinct = candidates.find(
        (c) => Array.from(parent.children).filter((sib) => safeMatches(sib, c)).length === 1,
      );
      segment = distinct ?? nthOfType(current);
    }

    parts.unshift(segment);
    const selector = parts.join(' > ');
    if (isUnique(el, selector)) return selector;

    current = parent;
    depth++;
  }

  return parts.join(' > ');
}

function safeMatches(el: Element, selector: string): boolean {
  try {
    return el.matches(selector);
  } catch {
    return false;
  }
}

export function xPathFor(el: Element): string {
  const id = el.getAttribute('id');
  if (id && rootOf(el) === el.ownerDocument && isUnique(el, `#${esc(id)}`)) {
    return `//*[@id="${escAttrValue(id)}"]`;
  }

  const parts: string[] = [];
  let current: Element | null = el;

  while (current && current.nodeType === Node.ELEMENT_NODE) {
    const tag = tagOf(current);
    const parent: Element | null = current.parentElement;
    if (!parent) {
      parts.unshift(`/${tag}`);
      break;
    }
    const sameTag = Array.from(parent.children).filter((c) => tagOf(c) === tag);
    const index = sameTag.indexOf(current) + 1;
    parts.unshift(sameTag.length > 1 ? `/${tag}[${index}]` : `/${tag}`);
    current = parent;
  }

  return parts.join('');
}

/** Readable ancestor trail, e.g. `body > main.content > section > button`. */
export function domPathFor(el: Element, maxDepth = 8): string {
  const chain: string[] = [];
  let current: Element | null = el;

  while (current && chain.length < maxDepth) {
    chain.unshift(describeElement(current));
    current = current.parentElement;
  }

  return chain.join(' > ');
}

/** Compact human label for one element: `button#submit.btn.primary`. */
export function describeElement(el: Element): string {
  const tag = tagOf(el);
  const id = el.getAttribute('id');
  const classes = stableClasses(el).slice(0, 2);
  const testId = el.getAttribute('data-testid') ?? el.getAttribute('data-test-id');

  let label = tag;
  if (id) label += `#${id}`;
  if (classes.length > 0) label += `.${classes.join('.')}`;
  if (testId) label += `[data-testid="${testId}"]`;
  return label;
}
