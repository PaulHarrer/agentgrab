/** Renders an ElementContext + a user request into a ready-to-paste prompt. */

import type { ElementContext } from './context';

function section(title: string, body: string | undefined | null): string {
  if (!body || !body.trim()) return '';
  return `### ${title}\n${body.trim()}\n\n`;
}

function keyValueList(entries: Record<string, string>, limit = 25): string {
  const keys = Object.keys(entries).slice(0, limit);
  if (keys.length === 0) return '';
  return keys.map((key) => `- \`${key}\`: ${entries[key]}`).join('\n');
}

export function buildPrompt(context: ElementContext, request: string): string {
  const task = request.trim() || '(describe the change you want here)';

  const sourceHints = context.sourceHints
    .map((hint) => {
      const parts = [hint.framework];
      if (hint.component) parts.push(`component \`${hint.component}\``);
      if (hint.file) parts.push(hint.file + (hint.line ? `:${hint.line}` : ''));
      return `- ${parts.join(' — ')}`;
    })
    .join('\n');

  const searchHints = context.searchHints.map((hint) => `- \`${hint}\``).join('\n');

  const location = [
    `- Page: ${context.pageTitle || '(untitled)'}`,
    `- URL: ${context.url}`,
    context.inIframe ? '- The element is inside an iframe.' : '',
    context.inShadowDom ? `- The element is inside a shadow root, host: \`${context.shadowHostPath}\`` : '',
  ]
    .filter(Boolean)
    .join('\n');

  const locators = [
    `- CSS selector: \`${context.cssSelector}\``,
    `- XPath: \`${context.xpath}\``,
    `- DOM path: \`${context.domPath}\``,
    `- Rendered box: ${context.rect.width}×${context.rect.height}px at (${context.rect.x}, ${context.rect.y}) in a ${context.viewport.width}×${context.viewport.height} viewport`,
  ].join('\n');

  return [
    '# Requested change',
    '',
    task,
    '',
    '## Target element',
    '',
    'The change applies to exactly one element on a live web page, described below.',
    '',
    section('Where', location),
    section('How to locate it', locators),
    section('Current markup', '```html\n' + context.outerHTML + '\n```'),
    section('Parent element', '```html\n' + context.parentHTML + '\n```'),
    section('Direct children', context.childSummary),
    section('Attributes', keyValueList(context.attributes)),
    section('Visible text', context.text ? `> ${context.text}` : ''),
    section('Computed styles (as currently rendered)', keyValueList(context.styles)),
    section('Source hints (from the running framework)', sourceHints),
    section('Strings to grep for in the codebase', searchHints),
    '## Instructions',
    '',
    [
      '1. Find the source code that renders this element. Use the grep strings and source hints above rather than guessing — the CSS selector describes the rendered DOM, which may be generated by a component, template, or CMS content.',
      '2. Confirm the code you found produces this exact element before editing. If the same component renders several instances, use the attributes and visible text above to change only the one described here.',
      '3. Apply the requested change at the source level. Keep the surrounding structure, class conventions, and styling approach used by the existing code — do not introduce inline styles or a new styling system if the project uses something else.',
      '4. Do not modify unrelated elements, and do not refactor beyond what the change requires.',
      '5. If the element cannot be located in the codebase, say so and list the files you checked instead of editing a best guess.',
    ].join('\n'),
    '',
  ]
    .filter((part) => part !== '')
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
